// ───────────── 日期工具 ─────────────
export const toDate = (iso: string) => {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
};
export const monthKey = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;

/** 这场展碰到的月份（month 类就是它的 month）。 */
export function monthsOf(f: Fair): string[] {
  if (f.kind === "month") return f.month ? [f.month] : [];
  const out = new Set<string>();
  for (const [a, b] of f.spans) {
    const cur = toDate(a);
    const end = toDate(b);
    while (cur <= end) {
      out.add(monthKey(cur));
      cur.setDate(cur.getDate() + 1);
    }
  }
  return [...out];
}

export function monthLabel(key: string, withYear = false) {
  const [y, m] = key.split("-").map(Number);
  return withYear ? `${y} 年 ${m} 月` : `${m} 月`;
}

// 三个分段按时间序渲染；放在文件末尾是因为这里用到上面定义的日期工具。
const PERIOD_ORDER: Record<Period, number> = { near: 0, spring: 1, summer: 2, autumn: 3 };
const firstDay = (f: Fair) => (f.spans.length ? toDate(f.spans[0][0]).getTime() : toDate(`${f.month ?? "2026-11"}-01`).getTime());
fairs.sort((a, b) => PERIOD_ORDER[a.period] - PERIOD_ORDER[b.period] || firstDay(a) - firstDay(b));
